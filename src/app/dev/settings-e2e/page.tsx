export default async function SettingsE2EPage({
  searchParams,
}: {
  searchParams: Promise<{
    area?: string;
    connectAgent?: string;
    document?: string;
    workspaceOnboarding?: string;
  }>;
}) {
  if (process.env.NODE_ENV !== "development") notFound();
  const params = await searchParams;
  const requestedArea = params.area;
  const area = requestedArea === "account"
    || requestedArea === "agents"
    || requestedArea === "site"
    || requestedArea === "organization"
    ? requestedArea
    : "workspace";
  return <SettingsShell
    area={area}
    currentDocumentId={params.document}
    initialConnectAgent={params.connectAgent === "1"}
    initialWorkspaceOnboarding={params.workspaceOnboarding === "1"}
    view={view}
  />;
}
