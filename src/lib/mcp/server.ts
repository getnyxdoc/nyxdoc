async function renderMutationToolResult(
  action: () => Record<string, unknown> | Promise<Record<string, unknown>>,
  receiptContext: McpMutationReceiptContext,
  responseMode?: McpResponseMode,
  publicBaseUrl = getAuthBaseUrl(),
) {
  try {
    const result = withPrimaryDocumentWebUrl(await action(), publicBaseUrl);
    const receipt = buildMcpMutationReceipt(result, receiptContext);
    const envelopedResult = {
      resultVersion: "1",
      operation: receiptContext.operation,
      ...result,
      receipt,
    };
    return renderToolResult(responseMode
      ? projectMutationResponse(receiptContext.operation, envelopedResult, responseMode)
      : envelopedResult, publicBaseUrl);
  } catch (error) {
    if (error instanceof z.ZodError) {
      const structuredContent = {
        error: mcpErrorMessage("INVALID_INPUT"),
        code: "INVALID_INPUT",
        errorSource: "runtime_validation",
        reason: "The tool input failed runtime validation.",
        issues: error.issues.slice(0, 20).map((issue) => ({
          code: issue.code,
          path: issue.path.map(String),
          message: issue.message,
        })),
      };
      return {
        isError: true,
        content: [{ type: "text" as const, text: JSON.stringify(structuredContent, null, 2) }],
        structuredContent,
      };
    }
    if (
      !(error instanceof DocumentServiceError)
      && !(error instanceof ApiTokenError)
      && !(error instanceof AuthorizationError)
      && !(error instanceof PresenceError)
      && !(error instanceof AdminActionRequestError)
      && !(error instanceof TaskServiceError)
      && !(error instanceof MediaServiceError)
    ) throw error;
    const code = error instanceof PresenceError ? "FORBIDDEN" : error.code;
    const structuredContent = {
      error: mcpErrorMessage(code),
      code,
      errorSource: "service",
      reason: error.message,
      ...(error instanceof DocumentServiceError || error instanceof TaskServiceError
        ? error.details ?? {}
        : {}),
    };
    return {
      isError: true,
      content: [{ type: "text" as const, text: JSON.stringify(structuredContent, null, 2) }],
      structuredContent,
    };
  }
}

