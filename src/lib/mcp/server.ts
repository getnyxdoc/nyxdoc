type OutlineProjectionOptions = {
  rootSectionId?: string;
  maxDepth?: number;
  includeHashes: boolean;
  includeBlockRanges: boolean;
  includeHeadingPath: boolean;
};

function projectDocumentOutline(
  sections: ReturnType<typeof deriveDocumentOutline>,
  options: OutlineProjectionOptions,
) {
  const root = options.rootSectionId
    ? sections.find((section) => section.sectionId === options.rootSectionId)
    : null;
  if (options.rootSectionId && !root) {
    throw new DocumentServiceError("NOT_FOUND", "The requested outline root section was not found.", {
      sectionId: options.rootSectionId,
    });
  }
  const selected = sections.filter((section) => {
    if (root && (
      section.startBlockIndex < root.startBlockIndex
      || section.endBlockIndex > root.endBlockIndex
    )) return false;
    const relativeDepth = root
      ? section.headingPath.length - root.headingPath.length + 1
      : section.headingPath.length;
    return options.maxDepth === undefined || relativeDepth <= options.maxDepth;
  });
  return selected.map((section) => ({
    sectionId: section.sectionId,
    level: section.level,
    title: section.title,
    parentSectionId: section.parentSectionId,
    blockCount: section.blockCount,
    ...(options.includeHashes ? { sectionHash: section.sectionHash } : {}),
    ...(options.includeBlockRanges ? {
      startBlockIndex: section.startBlockIndex,
      endBlockIndex: section.endBlockIndex,
    } : {}),
    ...(options.includeHeadingPath ? { headingPath: section.headingPath } : {}),
  }));
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return Boolean(value) && typeof value === "object" && !Array.isArray(value);
}

function linkDocumentWithWebUrl(
  workspaceId: string,
  documentId: string,
  value: Record<string, unknown>,
  publicBaseUrl: string,
) {
  return {
    ...value,
    webUrl: getDocumentWebUrl(workspaceId, documentId, publicBaseUrl),
  };
}

function withPrimaryDocumentWebUrl(
  payload: Record<string, unknown>,
  publicBaseUrl: string,
) {
  const workspaceId = typeof payload.workspaceId === "string"
    ? payload.workspaceId
    : null;
  if (!workspaceId) return payload;

  const document = isRecord(payload.document) ? payload.document : null;
  const workingDocument = isRecord(payload.workingDocument)
    ? payload.workingDocument
    : null;
  const documentId = typeof payload.documentId === "string"
    ? payload.documentId
    : typeof document?.id === "string"
      ? document.id
      : typeof workingDocument?.documentId === "string"
        ? workingDocument.documentId
        : null;
  if (!documentId) return payload;

  return {
    ...payload,
    webUrl: getDocumentWebUrl(workspaceId, documentId, publicBaseUrl),
    ...(document && typeof document.id === "string"
      ? {
        document: linkDocumentWithWebUrl(
          workspaceId,
          document.id,
          document,
          publicBaseUrl,
        ),
      }
      : {}),
    ...(workingDocument && typeof workingDocument.documentId === "string"
      ? {
        workingDocument: linkDocumentWithWebUrl(
          workspaceId,
          workingDocument.documentId,
          workingDocument,
          publicBaseUrl,
        ),
      }
      : {}),
  };
}

function compactToolValue(value: unknown, key: string | null = null, depth = 0): unknown {
  if (value === null || typeof value === "number" || typeof value === "boolean") return value;
  if (typeof value === "string") {
    if (key && /^(rawKey|rawToken|bearerToken|connectionKey)$/i.test(key)) {
      return "[available only in structuredContent]";
    }
    if (key === "markdown" || key === "json") return { characterCount: value.length };
    return value.length > 240 ? `${value.slice(0, 237)}...` : value;
  }
  if (Array.isArray(value)) {
    if (value.length <= 8 && value.every((item) => item === null || ["string", "number", "boolean"].includes(typeof item))) {
      return value;
    }
    return { itemCount: value.length };
  }
  if (!isRecord(value)) return String(value);

  if (key === "content" && Array.isArray(value.blocks)) {
    return {
      schemaVersion: value.schemaVersion,
      blockCount: value.blocks.length,
    };
  }
  if (depth >= 2) return { fields: Object.keys(value) };

  const summary: Record<string, unknown> = {};
  for (const [childKey, childValue] of Object.entries(value)) {
    if (childKey === "jsonSchema") {
      summary[childKey] = "[available in structuredContent]";
      continue;
    }
    summary[childKey] = compactToolValue(childValue, childKey, depth + 1);
  }
  return summary;
}

function renderToolResult(
  value: Record<string, unknown>,
  publicBaseUrl: string,
) {
  const linkedValue = withPrimaryDocumentWebUrl(value, publicBaseUrl);
  const textSummary = {
    result: compactToolValue(linkedValue),
    fullResult: "Use structuredContent for the complete machine-readable result.",
  };
  return {
    content: [{ type: "text" as const, text: JSON.stringify(textSummary, null, 2) }],
    structuredContent: linkedValue,
  };
}

function renderProjectedReadPayload(
  operation: string,
  payload: Record<string, unknown>,
  omittedFields: string[] = [],
  publicBaseUrl = getAuthBaseUrl(),
) {
  const linkedPayload = withPrimaryDocumentWebUrl(payload, publicBaseUrl);
  const result: Record<string, unknown> = {
    resultVersion: "1",
    operation,
    ...linkedPayload,
    ...canonicalDraftFields(linkedPayload),
  };
  result.response = {
    omittedFields,
    estimatedBytes: Buffer.byteLength(JSON.stringify(result), "utf8"),
  };
  return result;
}

