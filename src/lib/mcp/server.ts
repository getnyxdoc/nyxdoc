// available on demand through get_schema, and every operation is parsed again
// with the strict runtime schema before it reaches the command service.
const mcpPatchBlockSchema = z.record(z.string(), z.unknown()).describe(
  "One AST v2 top-level body block. Do not insert the separate page title as a leading heading. Call get_schema(name=document_content) only when the authoritative JSON Schema is needed.",
);
